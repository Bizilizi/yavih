"""Which yavih source commit is running.

Two environments that each ``pip install git+…@main`` at different times run different code under similar
versions; this module names the commit so the difference is recorded (sidecars, results) instead of guessed.

Resolution, once per process on the first call, cached:

1. ``git``: the running package directory is ``<top>/src/yavih`` of a git work tree (a source checkout or an editable
   install): ``git rev-parse HEAD`` there. A non-editable install that merely sits inside a checkout
   (``.venv/lib/…/site-packages/yavih``) is not mistaken for it. A checkout's ``_version.py`` is not consulted for the
   commit: setuptools-scm wrote it at install time, and the tree has moved on since.
2. ``build``: an installed wheel's ``yavih/_version.py``, generated by setuptools-scm at build time
   (``__commit_id__`` = ``"g"`` + the full commit, ``__dirty__``). A version file without a full commit (a wheel
   built from an sdist, or without git metadata) means "unknown".
3. ``None``.

A commit is the full 40-hex (or 64-hex) object name, suffixed ``+dirty`` when tracked files differ from it
(``git status --porcelain --untracked-files=no``; untracked files are ignored, so a stray ``runs/`` or scratch file
does not mark a tree dirty; setuptools-scm applies the same rule through ``git describe --dirty``). Git is called
with a short timeout, never writes the index (``GIT_OPTIONAL_LOCKS=0``) and never raises; any failure is "unknown".

Stdlib-only, nothing runs at import (``import yavih.buildinfo`` is free).
"""

from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path
from typing import Any

__all__ = ["commit", "describe", "git_commit", "stamped_commit"]

#: Per git call, seconds. A network filesystem makes ``git status`` take a few hundred milliseconds.
GIT_TIMEOUT_S = 5.0
DIRTY_SUFFIX = "+dirty"
_COMMIT_RE = re.compile(r"^(?:[0-9a-f]{40}|[0-9a-f]{64})(?:\+dirty)?$")
_PKG_DIR = Path(__file__).resolve().parent

_cache: dict[str, Any] | None = None


def _valid(c: object) -> str | None:
    return c if isinstance(c, str) and _COMMIT_RE.match(c) else None


def _git(cwd: Path, *args: str) -> str | None:
    """``git -C cwd args…`` stdout (stripped), or None on any failure, a non-zero exit or the timeout."""
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}  # no GIT_DIR / GIT_WORK_TREE redirection
    env["GIT_OPTIONAL_LOCKS"] = "0"  # git status must not refresh-and-write the index of a tree others are editing
    try:
        proc = subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True, env=env,
                              timeout=GIT_TIMEOUT_S, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError, ValueError):
        return None
    return proc.stdout.strip() if proc.returncode == 0 else None


def git_commit(source_root: Path | str) -> str | None:
    """The commit of the yavih git work tree whose top level is ``source_root`` (it must hold ``src/yavih``),
    ``+dirty`` when tracked files are modified; None when ``source_root`` is not such a top level. Never raises."""
    try:
        root = Path(source_root).resolve()
        out = _git(root, "rev-parse", "--show-toplevel", "HEAD")
        if out is None:
            return None
        lines = out.splitlines()
        if len(lines) != 2 or Path(lines[0]).resolve() != root or not (root / "src" / "yavih").is_dir():
            return None
        head = _valid(lines[1])
        if head is None or head.endswith(DIRTY_SUFFIX):
            return None
        status = _git(root, "status", "--porcelain", "--untracked-files=no")
        return head + DIRTY_SUFFIX if status else head  # status None (git failed) -> report the clean head
    except Exception:  # noqa: BLE001 - provenance must never break a run
        return None


def stamped_commit(node: object, dirty: object = False) -> str | None:
    """The commit a setuptools-scm version file records: ``node`` is ``"g"`` + the full hex object name (or the bare
    name); ``+dirty`` when ``dirty is True``. None for anything else (None, an abbreviated node, a non-string)."""
    if not isinstance(node, str):
        return None
    c = _valid(node[1:] if node.startswith("g") else node)
    if c is None or c.endswith(DIRTY_SUFFIX):
        return None
    return c + DIRTY_SUFFIX if dirty is True else c


def _from_build() -> tuple[str | None, str | None] | None:
    """``(commit, version)`` from the generated ``yavih._version`` when it names a full commit, else None."""
    try:
        from yavih import _version  # type: ignore[attr-defined]  # generated file

        c = stamped_commit(getattr(_version, "__commit_id__", None), getattr(_version, "__dirty__", False))
        v = getattr(_version, "__version__", None)
    except Exception:  # noqa: BLE001 - ImportError without a build; anything else is a broken file, i.e. unknown
        return None
    return None if c is None else (c, v if isinstance(v, str) else None)


def _in_checkout_layout() -> bool:
    """The package directory is ``<top>/src/yavih`` (a source checkout or an editable install); no git call."""
    return _PKG_DIR.name == "yavih" and _PKG_DIR.parent.name == "src"


def _from_checkout() -> str | None:
    """The commit when this package directory is ``<top>/src/yavih`` of a git work tree."""
    try:
        if not _in_checkout_layout():
            return None
        return git_commit(_PKG_DIR.parent.parent)
    except Exception:  # noqa: BLE001
        return None


def _package_version() -> str | None:
    try:
        from yavih.versions import __version__  # lazy: versions.py may itself use this module

        return __version__
    except Exception:  # noqa: BLE001
        return None


def _resolve() -> dict[str, Any]:
    global _cache
    if _cache is None:
        info: dict[str, Any] = {"version": None, "commit": None, "source": None}
        try:
            if _in_checkout_layout():
                c = _from_checkout()
                if c is not None:
                    info.update(commit=c, source="git")
            else:
                built = _from_build()
                if built is not None:
                    info.update(commit=built[0], version=built[1], source="build")
            if info["version"] is None:
                info["version"] = _package_version()
        except Exception:  # noqa: BLE001
            pass
        _cache = info
    return _cache


def commit() -> str | None:
    """The full yavih source commit (``+dirty`` suffix when the tree had modified tracked files), or None when
    unknown. Resolved on the first call (one or two ``git`` calls at most in a checkout), cached; never raises."""
    return _resolve()["commit"]


def describe() -> dict[str, Any]:
    """``{"version": str | None, "commit": str | None, "source": "build" | "git" | None}`` (a fresh dict).
    ``version`` is the version file's ``__version__`` for a build, else ``yavih.versions.__version__``."""
    return dict(_resolve())


def _reset_cache() -> None:
    """Forget the resolved result (tests)."""
    global _cache
    _cache = None
